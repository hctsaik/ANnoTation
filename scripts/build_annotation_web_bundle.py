"""Build a locked, one-folder Windows bundle of the React web service."""

from __future__ import annotations

import argparse
from importlib.metadata import PackageNotFoundError, version
import json
import os
import platform
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path


MARKER = ".annotation-web-package-output"


def _verify_locked_environment(requirements: Path) -> None:
    mismatches: list[str] = []
    for raw_line in requirements.read_text(encoding="utf-8").splitlines():
        line = raw_line.split("#", 1)[0].strip()
        if not line:
            continue
        name, separator, expected = line.partition("==")
        if not separator:
            raise SystemExit(f"Bundle requirements must pin exact versions: {line}")
        try:
            actual = version(name.strip())
        except PackageNotFoundError:
            actual = "not installed"
        if actual != expected.strip():
            mismatches.append(f"{name.strip()}: expected {expected.strip()}, found {actual}")
    if mismatches:
        raise SystemExit(
            "The active Python environment does not match requirements-web-package.txt:\n"
            + "\n".join(f"- {item}" for item in mismatches)
        )


def _run(command: list[str], *, cwd: Path) -> None:
    print("+", subprocess.list2cmdline(command), flush=True)
    subprocess.run(command, cwd=cwd, check=True)


def _prepare_output(output: Path, allowed_root: Path) -> None:
    output = output.resolve()
    allowed_root = allowed_root.resolve()
    if output == allowed_root or not output.is_relative_to(allowed_root):
        raise SystemExit(f"Package output must be a child of {allowed_root}: {output}")
    if output.exists():
        if not output.is_dir() or not (output / MARKER).is_file():
            raise SystemExit(
                f"Refusing to replace an unowned package output: {output}. "
                f"Use a new --output path or remove the generated bundle after inspection."
            )
        shutil.rmtree(output)
    output.mkdir(parents=True)
    (output / MARKER).write_text("Generated by scripts/build_annotation_web_bundle.py\n", encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, help="Generated output directory under repository dist/")
    parser.add_argument("--skip-frontend-build", action="store_true")
    args = parser.parse_args()

    if os.name != "nt":
        raise SystemExit("The current desktop-service bundle profile targets Windows only.")
    if sys.version_info[:2] != (3, 11):
        raise SystemExit(f"Use the locked CPython 3.11 environment; found {sys.version.split()[0]}.")

    root = Path(__file__).resolve().parents[1]
    _verify_locked_environment(root / "requirements-web-package.txt")
    web_dir = root / "web"
    output = (args.output or (root / "dist" / "annotation-web")).resolve()
    allowed_root = root / "dist"

    if not args.skip_frontend_build:
        npm = shutil.which("npm")
        if not npm:
            raise SystemExit("npm was not found; install the Node version documented in README.md.")
        _run([npm, "run", "build"], cwd=web_dir)
    frontend = web_dir / "dist"
    if not (frontend / "index.html").is_file():
        raise SystemExit("React build is missing; run npm run build in web/ first.")

    try:
        import PyInstaller  # noqa: F401
        import PIL  # noqa: F401
        import requests  # noqa: F401
    except ImportError as exc:
        raise SystemExit(
            "Install the locked bundle environment with "
            "py -3.11-64 -m pip install -r requirements-web-package.txt"
        ) from exc

    _prepare_output(output, allowed_root)
    separator = os.pathsep
    data_dirs = ("annotation_runtime", "domain", "modules")
    command = [
        sys.executable, "-m", "PyInstaller",
        "--clean", "--noconfirm", "--onedir", "--console",
        "--name", "annotation-service",
        "--distpath", str(output),
        "--add-data", f"{frontend}{separator}web/dist",
        "--collect-all", "PIL",
        "--collect-all", "requests",
        "--collect-all", "certifi",
        "--collect-all", "httpx",
    ]
    for directory in data_dirs:
        command.extend(["--add-data", f"{root / directory}{separator}{directory}"])
    for module in (
        "ultralytics", "torch", "torchvision", "cv2", "numpy", "cryptography", "psutil",
    ):
        command.extend(["--exclude-module", module])
    command.append(str(root / "scripts" / "annotation_service_entry.py"))

    with tempfile.TemporaryDirectory(prefix="annotation-pyinstaller-") as temp_dir:
        temp = Path(temp_dir)
        command.extend(["--workpath", str(temp / "build"), "--specpath", str(temp / "spec")])
        _run(command, cwd=root)

    package = output / "annotation-service"
    executable = package / "annotation-service.exe"
    if not executable.is_file():
        raise SystemExit(f"PyInstaller did not produce the expected executable: {executable}")
    manifest = {
        "schema_version": 1,
        "application": "ANnoTation React Web local service",
        "target_os": "windows",
        "python_version": platform.python_version(),
        "python_architecture": platform.machine(),
        "executable": "annotation-service/annotation-service.exe",
        "static_ui": "annotation-service/_internal/web/dist",
        "ai_runtime_included": False,
        "ai_runtime_note": "YOLO runtime remains optional and requires a separate approved profile.",
    }
    (output / "annotation-package.json").write_text(
        json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8",
    )
    print(f"Package ready: {output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
